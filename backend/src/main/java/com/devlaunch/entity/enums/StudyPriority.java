package com.devlaunch.entity.enums;

/**
 * Enumeration of priority levels for a study session or task.
 * <p>
 * Defines the relative importance of a study plan entry, allowing
 * users to prioritise their learning activities based on urgency
 * or significance.
 * </p>
 */
public enum StudyPriority {

    /**
     * Low priority — non-urgent or optional study activity.
     */
    LOW,

    /**
     * Medium priority — moderately important study activity.
     */
    MEDIUM,

    /**
     * High priority — critical or time-sensitive study activity.
     */
    HIGH

}
